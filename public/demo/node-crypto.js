// 브라우저 데모에서 서버 코드(src/)가 부르는 node:crypto 대신. 데모 페이지의 import map이 'node:crypto'를 이 파일로 잇는다.
// 서버 코드가 쓰는 만큼만 있다: randomUUID, randomBytes(n).toString('base64url'|'hex'), createHash('sha256')(동기).
// 데모의 지문(배분 캐시·기억 키)과 초대·QR 토큰에만 쓰고, 비밀을 지키는 데는 쓰지 않는다

const toHex = (bytes) => [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('');
const toBase64url = (bytes) => btoa(String.fromCharCode(...bytes)).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const encoded = (bytes) => ({
  toString: (encoding = 'hex') => (encoding === 'base64url' ? toBase64url(bytes) : toHex(bytes)),
});

export const randomUUID = () => globalThis.crypto.randomUUID();

export function randomBytes(n) {
  return encoded(globalThis.crypto.getRandomValues(new Uint8Array(n)));
}

