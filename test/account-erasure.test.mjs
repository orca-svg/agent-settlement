import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MemoryStore } from '../src/store/memory.mjs';
import { seedDemoRoom } from '../src/dev/seed.mjs';
import { ledger } from '../public/core.js';
import { createApp } from '../src/app.mjs';
import { validateExpense } from '../src/expenses/validate.mjs';
import { signQrToken, verifyQrToken } from '../src/payments/qr.mjs';
import { encryptedStore } from '../src/store/encrypted.mjs';

test('eraseUser preserves shared amounts, unlinks identity per room and removes private copies', async () => {
  const store = new MemoryStore();
  await seedDemoRoom(store, { id: 'one' });
  await seedDemoRoom(store, { id: 'two' });
  await store.put('users', { id: 'me', name: 'Alice', color: '#112233' });
  await store.put('locationEvidence', { id: 'loc', roomId: 'one', uid: 'me', summary: 'PRIVATE LOCATION' });
  await store.put('locationConsents', { id: 'consent', roomId: 'one', uid: 'me' });
  const expenses = await store.list('expenses', { roomId: 'one' });
  const before = ledger(await store.get('rooms', 'one'), expenses, 'actual');
  const owned = expenses.find(e => e.payer === 'me');
  await store.put('receipts', { id: owned.id, roomId: 'one', data: 'PRIVATE PHOTO' });
  await store.put('transfers', { id: 'one:me:cs', roomId: 'one', from: 'me', to: 'cs', amount: 100, link: 'PRIVATE LINK', fallback: { accountNo: '123' } });
  await store.put('disputes', { id: 'd', roomId: 'one', by: 'me', status: 'proposed', claim: 'PRIVATE CLAIM', evidence: [{ locationId: 'loc', summary: 'PRIVATE LOCATION' }], proposal: { summary: 'PRIVATE CLAIM' }, agreedBy: ['me'] });
  await store.appendEvent('one', { from: 'me', to: 'all', kind: 'dispute', text: 'PRIVATE LOCATION', meta: 'Alice', action: { type: 'answer_invoice', ref: 'one:me:cs', for: 'me' } });
  await store.appendEvent('unrelated', { from: 'other', text: 'keep me' });
  const { removedLinks } = await store.eraseUser('me');
  const room = await store.get('rooms', 'one');
  const deleted = room.members.find(m => m.deleted);
  assert.ok(deleted.uid.startsWith('deleted-'));
  assert.equal(deleted.name, '탈퇴한 사용자');
  assert.notEqual(deleted.uid, (await store.get('rooms', 'two')).members.find(m => m.deleted).uid);
  assert.deepEqual(ledger(room, await store.list('expenses', { roomId: 'one' }), 'actual')[deleted.uid], before.me);
  for (const uid of ['cs', 'yh', 'ms']) assert.deepEqual(ledger(room, await store.list('expenses', { roomId: 'one' }), 'actual')[uid], before[uid]);
  assert.equal(await store.get('users', 'me'), null);
  assert.equal(await store.get('agents', 'me'), null);
  assert.equal(await store.get('receipts', owned.id), null);
  assert.deepEqual(await store.list('locationEvidence', { uid: 'me' }), []);
  assert.deepEqual(await store.list('locationConsents', { uid: 'me' }), []);
  assert.deepEqual(removedLinks, ['PRIVATE LINK']);
  const transfers = await store.list('transfers');
  assert.equal(transfers[0].amount, 100);
  assert.equal(transfers[0].link, null);
  assert.equal(transfers[0].fallback, null);
  assert.equal(transfers[0].from, deleted.uid);
  assert.ok(!JSON.stringify(await store.listEvents('one')).includes('PRIVATE'));
  assert.equal((await store.listEvents('unrelated'))[0].text, 'keep me');
  assert.equal((await store.get('disputes', 'd')).proposal, undefined);
  assert.equal((await store.listEvents('one')).at(-1).kind, 'account_erased');
  assert.equal(validateExpense({ ...owned, payer: deleted.uid, present: [deleted.uid] }, room).ok, false);
  const snapshot = JSON.stringify([...store.cols]);
  await store.eraseUser('me');
  assert.equal(JSON.stringify([...store.cols]), snapshot); // retry is idempotent
});

test('authenticated deletion unlinks a room member, invalidates QR and rejects stale access', async t => {
  const store = encryptedStore(new MemoryStore(), Buffer.alloc(32, 7));
  await seedDemoRoom(store, { id: 'room' });
  await store.put('transfers', { id: 'room:me:cs', roomId: 'room', from: 'me', to: 'cs', amount: 100, link: 'supertoss://current-account', fallback: { accountNo: '123' } });
  await store.put('transfers', { id: 'room:ms:cs', roomId: 'room', from: 'ms', to: 'cs', amount: 200, link: 'supertoss://unrelated-account', fallback: { accountNo: '456' } });
  const currentQr = signQrToken('supertoss://current-account');
  const oldQr = signQrToken('supertoss://old-account', { subjectUids: ['me', 'cs'] });
  const authTime = Math.floor(Date.now() / 1000) - 600; // 10분 전에 로그인
  const removed = [];
  const server = createApp({ store, auth: { verifyIdToken: async () => ({ uid: 'me', auth_time: authTime }), deleteUser: async uid => removed.push(uid) } });
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  t.after(() => { server.closeAllConnections(); server.close(); });
  const req = (path, method = 'GET') => fetch(`http://127.0.0.1:${server.address().port}${path}`, { method, headers: { authorization: 'Bearer valid' } });
  // 오래전에 로그인했어도 다시 로그인 창 없이 탈퇴한다. 되돌릴 수 없으니 화면에서 한 번 확인을 받는다
  assert.ok((await store.get('rooms', 'room')).members.some(m => m.uid === 'me'));
  assert.equal((await req('/api/me/delete', 'POST')).status, 200);
  assert.deepEqual(removed, ['me']);
  assert.equal(verifyQrToken(oldQr), null);
  assert.equal(verifyQrToken(currentQr), null);
  const transfers = await store.list('transfers');
  assert.equal(transfers.find(t => t.amount === 100).link, null);
  assert.equal(transfers.find(t => t.amount === 200).fallback.accountNo, '456');
  assert.equal((await req('/api/me/deletion')).headers.get('cache-control'), 'no-store');
  assert.equal((await req('/api/rooms/room')).status, 401);
  assert.equal((await req('/api/me', 'POST')).status, 401);
  assert.deepEqual(await (await req('/api/me/deletion')).json(), { pending: true });
});
